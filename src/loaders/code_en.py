"""MBPP+ and LiveCodeBench: English only; Italian files are placeholders with matching ids.

Only the problem statement is to be translated; tests are shared and unchanged.
"""

import json
from pathlib import Path

import pandas as pd

from .. import prompts
from ..schema import Built, Issues, Item, placeholder, user
from . import translated
from . import hf_file, register, release_file, source

MBPP = "evalplus/mbppplus"
# EvalPlus's own MBPP+ release: source of the prompt text (the Hub copy keeps source URLs
# that EvalPlus strips in 18 tasks). Tests still come from the Hub copy.
MBPP_RELEASE = "https://github.com/evalplus/mbppplus_release/releases/download/v0.2.0/MbppPlus.jsonl.gz"
MBPP_RELEASE_SHA256 = "af43697e8791c4c149bdfd6b489d8b5412507551ac20e28a439f650b8225db63"
MBPP_TRANSLATION_RULE = (
    "Translate only the task sentence(s) of the docstring (meta.source_prompt) into Italian. Keep unchanged: the assert "
    "line, function and variable names, and every quoted value. Then build the prompt with prompts.evalplus_prompt('it', "
    "translated_docstring)."
)
LCB = "livecodebench/code_generation_lite"
# Olmo 3 reports "LiveCodeBench v3": OLMES loads version_tag="release_v3", the
# cumulative release made of these three files (contests 2023-05 to 2024-08).
LCB_FILES = ["test.jsonl", "test2.jsonl", "test3.jsonl"]
LCB_RELEASE = "release_v3"
LCB_FIXED_OUTPUT = json.loads((Path(__file__).parent / "lcb_fixed_output_words.json").read_text())["words"]
LCB_TRANSLATION_RULE = (
    "Translate the problem statement (meta.source_prompt) into Italian, section headings included (Input, Output, Constraints, "
    "Sample Input/Output, Example, Explanation). Keep unchanged: sample inputs and outputs, code, identifiers, variable names, "
    "formulas, constraints written in symbols, every quoted value, and every word the program must print or return, "
    "even when it is not in quotes (e.g. 'print Yes; otherwise, print No' -> 'stampa Yes; altrimenti, stampa No'; also "
    "First/Second, names such as Takahashi and Aoki, Draw, Impossible). Then build the prompt with prompts.lcb_messages('it', "
    "translated_statement, starter_code): system message and format instructions are already in Italian."
)


@register("mbppplus")
def mbppplus() -> Built:
    import gzip

    issues = Issues()
    df = pd.read_parquet(hf_file(MBPP, "data/test-00000-of-00001-d5781c9c51e02795.parquet"))
    with gzip.open(release_file(MBPP_RELEASE, MBPP_RELEASE_SHA256), "rt", encoding="utf-8") as f:
        release = {r["task_id"]: r for r in map(json.loads, f)}
    en = []
    for row in df.to_dict("records"):
        task_id = f"Mbpp/{row['task_id']}"
        tests = [str(t) for t in row["test_list"]]
        rel = release.get(task_id)
        if rel is None:
            issues.add("missing_in_release", "task not in the EvalPlus release file", task_id, "en")
            continue
        if not tests or tests[0] not in rel["prompt"]:
            issues.add("prompt_test_mismatch", "the release prompt does not show the Hub copy's first test", task_id, "en")
        if f'"""\n{row["prompt"]}\n' not in rel["prompt"]:
            issues.add("prompt_text_differs_from_hub", "EvalPlus's prompt differs from the Hub copy's text (source URL removed, or text edited)", task_id, "en")
        en.append(
            Item(
                id=task_id,
                lang="en",
                messages=user(prompts.evalplus_prompt("en", rel["prompt"])),
                answer=None,
                scorer="code_exec",
                meta={
                    "test": row["test"],  # MBPP+ test script: calls the function by name
                    "test_format": "script",
                    "test_imports": [str(t) for t in row["test_imports"]],
                    "base_tests": tests,
                    "entry_point": rel["entry_point"],
                    "canonical_solution": row["code"],
                    "source_prompt": rel["prompt"],  # EvalPlus docstring: task text + one assert
                    "hub_prompt": row["prompt"],
                    "template": "evalplus-instruct-v1",
                },
            )
        )
    it = [
        placeholder(e, translate=["source_prompt"], translation_rule=MBPP_TRANSLATION_RULE, template="evalplus-instruct-v1",
                    keep=["test", "test_format", "test_imports", "entry_point"])
        for e in en
    ]
    it = translated.fill("mbppplus", en, it, issues)
    return Built(
        {"it": it, "en": en},
        issues,
        {
            "name": "MBPP+",
            "source": f"{source(MBPP)} (tests); prompts from EvalPlus's release {MBPP_RELEASE} (sha256 {MBPP_RELEASE_SHA256[:12]})",
            "paper": "Liu et al., 2023, Is Your Code Generated by ChatGPT Really Correct? (EvalPlus, NeurIPS 2023); Austin et al., 2021 (MBPP)",
            "licence": "Apache 2.0",
            "scorer": "code_exec (sandboxed) with the MBPP+ tests",
            "notes": [
                "Prompt (decision 2026-10-15): EvalPlus's own chat instruction, \"Please provide a self-contained Python script that solves the following problem in a markdown code block:\", then EvalPlus's task prompt (a docstring with the task text and one assert, which fixes the function name) in a ``` block, exactly as EvalPlus builds it. EvalPlus also prefills the assistant turn with \"Below is a Python script ...\"; we do not, so the model can think first. Italian instruction: our translation.",
                "Alternatives considered: Olmo 3's (task text + the reference solution's opening up to its first ':' + 'Here is the completed function:'), rejected because the cut breaks signatures with type hints (Mbpp/4, Mbpp/6) and leaks the solution's imports; our own earlier wording (code-mbpp-v1).",
                "The prompt text is taken from EvalPlus's release file, not the Hub copy: 18 Hub prompts still end with the source URL (geeksforgeeks), which EvalPlus removes; in 2 of them (Mbpp/752, Mbpp/753) EvalPlus's text also differs otherwise. Logged as prompt_text_differs_from_hub.",
                "No task expects a fixed English word as output (EvalPlus made the old 'Found a match!' tasks return booleans), so translation only has to keep quoted values and names.",
                "Italian (2026-11-02): our translation, TranslateGemma 27B (Infomaniak-AI/vllm-translategemma-27b-it) on Cineca, prose only, code and samples protected by the pipeline; every row re-checked at build time (src/loaders/translated.py; pinned by config/translation/manifest.json). Provenance in meta.translation. Rule in meta.translation_rule. Tests are identical for both languages.",
            ],
        },
    )


@register("livecodebench")
def livecodebench() -> Built:
    issues = Issues()
    en = []
    for filename in LCB_FILES:
        with open(hf_file(LCB, filename), encoding="utf-8") as f:
            for line in f:
                row = json.loads(line)
                starter = row["starter_code"]
                metadata = json.loads(row["metadata"]) if row["metadata"] else {}
                public = json.loads(row["public_test_cases"])
                if starter.strip() and "func_name" not in metadata:
                    issues.add("no_func_name", "starter code without metadata.func_name", row["question_id"], "en")
                en.append(
                    Item(
                        id=f"lcb-{row['question_id']}",
                        lang="en",
                        messages=prompts.lcb_messages("en", row["question_content"], starter),
                        answer=None,
                        scorer="code_exec",
                        meta={
                            "test_format": "livecodebench",
                            "question_id": row["question_id"],
                            "question_title": row["question_title"],
                            "platform": row["platform"],
                            "contest_id": row["contest_id"],
                            "contest_date": row["contest_date"],
                            "difficulty": row["difficulty"],
                            "starter_code": starter,
                            "func_name": metadata.get("func_name"),
                            "public_tests": public,
                            # Private tests are ~2.5 GB once decoded: they stay in the Hub cache
                            # and the scorer reads them from there, untouched.
                            "private_tests_ref": {"repo": LCB, "file": filename, "question_id": row["question_id"]},
                            # English words the tests expect in the output: must survive translation untouched
                            "fixed_output_words": LCB_FIXED_OUTPUT.get(f"lcb-{row['question_id']}", []),
                            "source_prompt": row["question_content"],
                            "template": "lcb-official",
                        },
                    )
                )
    ids = [e.id for e in en]
    if len(set(ids)) != len(ids):
        issues.add("duplicate_ids", f"{len(ids) - len(set(ids))} duplicated question ids")
    dates = sorted(e.meta["contest_date"][:10] for e in en)
    it = [
        placeholder(e, translate=["source_prompt"], translation_rule=LCB_TRANSLATION_RULE, template="lcb-official",
                    keep=["starter_code", "public_tests", "private_tests_ref"],
                    fixed_output_words=e.meta["fixed_output_words"])
        for e in en
    ]
    it = translated.fill("livecodebench", en, it, issues)
    return Built(
        {"it": it, "en": en},
        issues,
        {
            "name": "LiveCodeBench (code generation, release_v3)",
            "source": source(LCB) + f" ({', '.join(LCB_FILES)})",
            "paper": "Jain et al., 2024, LiveCodeBench (arXiv:2403.07974)",
            "licence": "CC (as declared on the dataset card); problems come from LeetCode and AtCoder",
            "scorer": "code_exec (sandboxed): all public and private tests must pass",
            "notes": [
                f"Window fixed to the one Olmo 3 uses: `{LCB_RELEASE}` of code_generation_lite (OLMES task livecodebench_codegeneration, revision release_v3; the paper calls it \"LiveCodeBench v3\"). {len(en)} problems, contests from {dates[0]} to {dates[-1]}.",
                "Italian (2026-11-02): our translation, TranslateGemma 27B (Infomaniak-AI/vllm-translategemma-27b-it) on Cineca, prose only, code and samples protected by the pipeline; every row re-checked at build time (src/loaders/translated.py; pinned by config/translation/manifest.json). Provenance in meta.translation. The statement is translated; starter code, sample inputs/outputs and tests stay as they are. The output words are Italian (src/loaders/lcb_output_words_it.json, e.g. Yes -> Sì): the statement uses them and the scorer maps the expected outputs of every test (meta.output_word_map; 56 problems). 5 sentences repaired by hand (meta.repaired): a masked \"No\" that was prose in 3 explanations, and the accepted spellings of the positive answer in 2 Codeforces problems.",
                "Prompt: LiveCodeBench's own (system message + Question/Format/Answer), as OLMES builds it. The Italian prompt is Italian throughout: system message, headings and format instructions are our translation (src/prompts.py, LCB['it']), plus the translated statement.",
                f"{sum(bool(e.meta['fixed_output_words']) for e in en)} problems expect fixed English words in the program's output (meta.fixed_output_words: Yes/No in 51, plus First/Second, Bat/Glove, Draw, Unreachable, undecidable, infinite, san, Alice/Bob). Often unquoted in the statement (\"print Yes; otherwise, print No\"), so a translation that renders them in Italian makes the item unsolvable. Found by scanning every test output; 28 more problems print letters that are not language (random strings, echoed input). Plan (2026-10-15): mask these words before translating, translate them by hand, and map the expected test outputs to the Italian words (README, translation queue).",
                "Alternative not used: Olmo 3's variant (OLMES livecodebench_codegeneration::olmo3:adapt) adds \"Provide CONCISE reasoning on how to arrive at the answer in the <think> </think> tag.\" under '### Format:'. Left out because models with built-in thinking already reason in that block.",
                "Private tests are not copied into data/: meta.private_tests_ref points to the row of the pinned Hub file and the scorer decodes it at run time.",
                "Olmo 3 settings for the code benchmarks: temperature 0.6, top-p 0.95, 10 samples, pass@1.",
            ],
        },
    )
